#!/usr/bin/env python3
"""Generate the Pydantic v2 DTOs of the contract bundle into src/aegis/contracts_gen.

The contracts in contracts/ are the only source: every `*.schema.json` outside contracts/fixtures
is fed to datamodel-code-generator, nothing here defines or patches a DTO by hand.

    python scripts/codegen.py            rewrite src/aegis/contracts_gen
    python scripts/codegen.py --check    fail (exit 1) when the committed DTOs differ

Determinism, so `--check` is meaningful (CI runs it on every pull request):

* schemas are copied to a temporary tree in sorted order; the contract files are only read, never
  edited, so a schema change and its regenerated DTOs land in the same commit;
* the root `title` of each copied schema is replaced by a name derived from its file path
  (`capability/approved-task.v2.schema.json` -> `ApprovedTask`), because the hand-written titles
  are Vietnamese prose and datamodel-code-generator would turn them into names such as
  `ApprovedtaskV2`. `$defs`/property names and every other keyword are untouched, and `$id` stays
  the contract URI, so cross-file `$ref`s keep resolving to the same resources;
* datamodel-code-generator is pinned in uv.lock and called with `--disable-timestamp`, then its
  output is formatted with ruff using this repository's pyproject.toml, so the bytes depend only on
  the contracts and the lockfile;
* only the package markers are rewritten after generation: datamodel-code-generator puts the input
  directory name in every generated `__init__.py`, and that name is a temporary path. Those files
  hold no models; every DTO module is written by the generator untouched.

A stale `src/aegis/contracts_gen` therefore cannot pass: `--check` compares the complete file set
and the bytes of every generated module, and prints the first differing files.
"""

from __future__ import annotations

import argparse
import difflib
import filecmp
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "contracts"
TARGET = ROOT / "src/aegis/contracts_gen"
GENERATOR = ["-m", "datamodel_code_generator"]
# datamodel-code-generator emits warnings for the semantic formats this bundle declares
# (`aegis-*`); those are enforced by the shared validator (aegis/validation.py) instead.
GENERATOR_ARGS = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.14",
    "--disable-timestamp",
    "--formatters",
    "ruff-check",
    "ruff-format",
]
ROOT_INIT_TEXT = '''"""Pydantic v2 DTOs generated from the contracts (see scripts/codegen.py).

Do not edit these models: change contracts/**/*.schema.json and run `make codegen`.
`make codegen-check` fails when this tree and the contracts disagree.
"""
'''
PACKAGE_INIT_TEXT = (
    '"""Contract DTOs for the ``{package}`` schema group (generated, do not edit)."""\n'
)


class CodegenError(RuntimeError):
    """The contracts cannot be generated; the message says what to fix."""


def schema_files() -> list[Path]:
    """Every contract JSON Schema, sorted; fixtures are data, not schemas."""
    files = sorted(p for p in CONTRACTS.rglob("*.schema.json") if "fixtures" not in p.parts)
    if not files:
        raise CodegenError(f"no *.schema.json under {CONTRACTS}")
    return files


def root_class_name(path: Path) -> str:
    """`contracts/capability/approved-task.v2.schema.json` -> `ApprovedTask`."""
    stem = path.name.removesuffix(".schema.json")
    stem = re.sub(r"\.v\d+$", "", stem)
    parts = [part for part in re.split(r"[^0-9A-Za-z]+", stem) if part]
    name = "".join(part[:1].upper() + part[1:] for part in parts)
    if not name:
        raise CodegenError(f"cannot derive a root class name from {path}")
    return name


def stage_schemas(stage: Path) -> None:
    for path in schema_files():
        document = json.loads(path.read_text(encoding="utf-8"))
        document["title"] = root_class_name(path)
        destination = stage / path.relative_to(CONTRACTS)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(
            json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )


def generate(output: Path) -> None:
    # The staging tree must live under the repository and be passed to the generator as a
    # relative path: datamodel-code-generator writes the input path into each module header, so
    # an absolute path would put a random temporary directory name into the generated bytes.
    stage = Path(tempfile.mkdtemp(prefix=".codegen-stage-", dir=ROOT))
    cache = Path(tempfile.mkdtemp(prefix="aegis-codegen-cache-"))
    try:
        stage_schemas(stage)
        output.mkdir(parents=True, exist_ok=True)
        environment = dict(os.environ)
        environment["PATH"] = (
            f"{Path(sys.executable).parent}{os.pathsep}{environment.get('PATH', '')}"
        )
        environment["PYTHONDONTWRITEBYTECODE"] = "1"
        # Keep ruff's cache out of the generated tree (it would otherwise be written next to
        # the modules and show up as a codegen difference).
        environment["RUFF_CACHE_DIR"] = str(cache)
        completed = subprocess.run(
            [
                sys.executable,
                *GENERATOR,
                "--input",
                stage.relative_to(ROOT).as_posix(),
                "--output",
                str(output),
                *GENERATOR_ARGS,
            ],
            cwd=ROOT,
            env=environment,
            capture_output=True,
            text=True,
            check=False,
        )
    finally:
        shutil.rmtree(stage, ignore_errors=True)
        shutil.rmtree(cache, ignore_errors=True)
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout).strip().splitlines()
        raise CodegenError(
            "datamodel-code-generator failed (exit "
            f"{completed.returncode}): {' / '.join(detail[-5:])}"
        )
    (output / "__init__.py").write_text(ROOT_INIT_TEXT, encoding="utf-8")
    # datamodel-code-generator names the input directory in every generated package
    # `__init__.py`; that name is a temporary path, so replace the header with a stable docstring
    # (these files hold no models - the DTOs live in the sibling modules).
    for package in sorted(path for path in output.rglob("__init__.py") if path.parent != output):
        name = package.parent.relative_to(output).as_posix()
        package.write_text(PACKAGE_INIT_TEXT.format(package=name), encoding="utf-8")


def generated_files(tree: Path) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for path in sorted(tree.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(tree)
        if any(part.startswith(".") or part == "__pycache__" for part in relative.parts):
            continue
        if relative.suffix == ".pyc":
            continue
        files[relative.as_posix()] = path
    return files


def compare(committed: Path, fresh: Path) -> tuple[list[str], list[str], list[str]]:
    committed_files = generated_files(committed) if committed.is_dir() else {}
    fresh_files = generated_files(fresh)
    missing = sorted(set(fresh_files) - set(committed_files))
    stale = sorted(set(committed_files) - set(fresh_files))
    changed = sorted(
        name
        for name in set(fresh_files) & set(committed_files)
        if not filecmp.cmp(committed_files[name], fresh_files[name], shallow=False)
    )
    return missing, stale, changed


def print_diff(committed: Path, fresh: Path, names: list[str], limit: int = 3) -> None:
    for name in names[:limit]:
        old = committed / name
        new = fresh / name
        if not old.is_file() or not new.is_file():
            continue
        diff = difflib.unified_diff(
            old.read_text(encoding="utf-8").splitlines(),
            new.read_text(encoding="utf-8").splitlines(),
            fromfile=f"committed/{name}",
            tofile=f"generated/{name}",
            lineterm="",
            n=3,
        )
        print("\n".join(list(diff)[:80]), file=sys.stderr)


def check(committed: Path = TARGET) -> int:
    with tempfile.TemporaryDirectory(prefix="aegis-codegen-check-") as fresh_dir:
        fresh = Path(fresh_dir)
        generate(fresh)
        missing, stale, changed = compare(committed, fresh)
        if not (missing or stale or changed):
            print(
                f"codegen-check: OK ({len(schema_files())} schemas, "
                f"{len(generated_files(committed))} committed files)"
            )
            return 0
        print(
            "codegen-check: FAILED - contracts and src/aegis/contracts_gen disagree",
            file=sys.stderr,
        )
        if missing:
            print(f"  not committed ({len(missing)}): {', '.join(missing[:10])}", file=sys.stderr)
        if stale:
            print(f"  no longer generated ({len(stale)}): {', '.join(stale[:10])}", file=sys.stderr)
        if changed:
            print(f"  changed ({len(changed)}): {', '.join(changed[:10])}", file=sys.stderr)
        print_diff(committed, fresh, missing + changed)
        print("run `make codegen` and commit the result", file=sys.stderr)
        return 1


def write(committed: Path = TARGET) -> int:
    with tempfile.TemporaryDirectory(prefix="aegis-codegen-write-") as fresh_dir:
        fresh = Path(fresh_dir)
        generate(fresh)
        if committed.exists():
            shutil.rmtree(committed)
        committed.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(fresh, committed)
    print(
        f"codegen: wrote {len(generated_files(committed))} files from "
        f"{len(schema_files())} schemas to {committed.relative_to(ROOT)}"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; fail when the committed DTOs differ from a fresh generation",
    )
    arguments = parser.parse_args(argv)
    try:
        return check() if arguments.check else write()
    except CodegenError as error:
        print(f"codegen: error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

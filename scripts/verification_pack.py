#!/usr/bin/env python3
"""Generate the deployment check packs from `contracts/verification/checks.v2.yaml`.

The contract registry is the source of truth. Two packs are derived from it and committed, because
M06 mounts exactly one of them for a job and M21/M06 compare the mounted bytes with the registry:

    deploy/lab/verify/checks.v2.yaml        every check (L1/C1 templates live in templates/)
    deploy/internet/verify/checks.v2.yaml   E1 checks only; no template, no Nuclei entry

The lab templates are authored under `deploy/lab/verify/templates/` (the only place L1 request
bytes exist); this script validates their pinned sha256 but never copies or rewrites them. The
internet pack must contain exactly its registry file: a stray L1 template there fails the check.

    python scripts/verification_pack.py            rewrite the two generated registries
    python scripts/verification_pack.py --check    fail (exit 1) when they drift

`pack_sha256` of each pack is printed; the deployment profile stores that value (S3) and M06
compares it with the mounted pack and the `check_pack_sha256` of the signed task.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from aegis.common.repo import repository_root
from aegis.common.verification import (
    CheckPack,
    VerificationCheck,
    load_checks,
    pack_sha256,
)

ROOT = repository_root()
LAB = ROOT / "deploy/lab/verify"
INTERNET = ROOT / "deploy/internet/verify"
HEADER = (
    "# Generated from contracts/verification/checks.v2.yaml by scripts/verification_pack.py.\n"
    "# Do not edit this file: change the contract registry and run `make verify-pack`.\n"
)
PACK_DIRECTORIES = (LAB, INTERNET)


def _entry(check: VerificationCheck) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "id": check.check_id,
        "title": check.title,
        "class": check.check_class,
        "labOnly": check.lab_only,
        "provider": check.provider,
        "appliesTo": {"findingRule": check.finding_rule},
    }
    if check.template is not None:
        entry["template"] = check.template
        entry["templateSha256"] = check.template_sha256
    entry["targets"] = {
        "positive": check.targets.positive,
        "controlPatchedTwin": check.targets.control_patched_twin,
        "controlBenign": check.targets.control_benign,
    }
    entry["requests"] = {"perTarget": check.per_target, "cap": check.request_cap}
    entry["oracle"] = check.oracle
    if check.expected_kind is not None:
        entry["expected"] = {"kind": check.expected_kind}
    return entry


def _document(checks: tuple[VerificationCheck, ...]) -> dict[str, Any]:
    return {
        "apiVersion": "aegis.io/v2",
        "kind": "VerificationCheckPack",
        "checks": [_entry(check) for check in checks],
    }


def lab_document(pack: CheckPack) -> dict[str, Any]:
    """Every check: the lab pack mounts the full registry plus the reviewed templates."""
    return _document(pack.checks)


def internet_document(pack: CheckPack) -> dict[str, Any]:
    """The E1-only projection: the internet profile never mounts an L1 template or Nuclei."""
    return _document(pack.e1())


def render(document: dict[str, Any]) -> str:
    body = yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


def expected_registries(pack: CheckPack) -> dict[Path, str]:
    return {
        LAB / "checks.v2.yaml": render(lab_document(pack)),
        INTERNET / "checks.v2.yaml": render(internet_document(pack)),
    }


def _files(directory: Path) -> list[str]:
    if not directory.is_dir():
        return []
    return sorted(
        path.relative_to(directory).as_posix()
        for path in directory.rglob("*")
        if path.is_file() or path.is_symlink()
    )


def _relative(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def check() -> list[str]:
    """Every way the committed packs can disagree with the contract registry."""
    problems: list[str] = []
    pack = load_checks(LAB / "templates")
    for path, expected in expected_registries(pack).items():
        relative = _relative(path)
        if not path.is_file() or path.is_symlink():
            problems.append(f"{relative}: missing (run `make verify-pack`)")
            continue
        if path.read_text(encoding="utf-8") != expected:
            problems.append(f"{relative}: differs from contracts/verification/checks.v2.yaml")

    declared = {check.template for check in pack.checks if check.template is not None}
    actual = set(_files(LAB / "templates"))
    for extra in sorted(actual - declared):
        problems.append(
            f"{_relative(LAB / 'templates' / extra)}: template is not declared by the registry"
        )
    for missing in sorted(declared - actual):
        problems.append(f"{_relative(LAB / 'templates' / missing)}: declared template is missing")

    internet_files = set(_files(INTERNET))
    for extra in sorted(internet_files - {"checks.v2.yaml"}):
        problems.append(
            f"{_relative(INTERNET / extra)}: the internet pack may contain only checks.v2.yaml"
        )
    if "checks.v2.yaml" not in internet_files:
        problems.append(
            f"{_relative(INTERNET / 'checks.v2.yaml')}: missing (run `make verify-pack`)"
        )
    return problems


def write() -> list[Path]:
    """Write the two generated registries; templates are authored, never touched."""
    pack = load_checks(LAB / "templates")
    written: list[Path] = []
    for path, content in expected_registries(pack).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; fail when the committed packs differ from the registry",
    )
    arguments = parser.parse_args(argv)
    try:
        if not arguments.check:
            for path in write():
                print(f"verification-pack: wrote {_relative(path)}")
        problems = check()
        lab_hash = pack_sha256(LAB) if LAB.is_dir() else "absent"
        internet_hash = pack_sha256(INTERNET) if INTERNET.is_dir() else "absent"
        if problems:
            for problem in problems:
                print(f"verification-pack: {problem}", file=sys.stderr)
            print(
                "verification-pack: FAILED - the committed packs disagree with the registry",
                file=sys.stderr,
            )
            return 1
        print(f"verification-pack: OK lab={lab_hash} internet={internet_hash}")
        return 0
    except (OSError, ValueError) as error:
        print(f"verification-pack: error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())

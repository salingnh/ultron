#!/usr/bin/env bash
# Reproducible Subfinder run against the authorized lab (G0.4c): the pinned G0.2 image asks
# the local passive-source stub over the internal lab network, through an /etc/hosts entry
# for crt.sh and a throwaway lab CA. It never reaches a third party, and the result is
# compared to the committed fixture.
set -euo pipefail
. "$(dirname "$0")/lib.sh"

require_cmd podman
require_cmd python3
load_images
require_lab_up

[ -s "$TLS_DIR/ca.crt" ] || die "lab CA is missing - run 'make lab-up' first"
health=$(podman inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$PASSIVE_CONTAINER")
[ "$health" = healthy ] || die "$PASSIVE_CONTAINER is not healthy ($health) - see 'make lab-status'"

run_dir=$(new_run_dir subfinder)
cat >"$run_dir/command.txt" <<EOF
# aegis-lab Subfinder run ($(date -u +%Y-%m-%dT%H:%M:%SZ))
image:    $AEGIS_LAB_SUBFINDER_IMAGE
network:  $LAB_NETWORK (internal); crt.sh -> $PASSIVE_IP via /etc/hosts (local stub)
ca:       deploy/lab/.run/tls/ca.crt (generated by make lab-up, SSL_CERT_FILE inside the run)
args:     -silent -json -d $LAB_ZONE -sources crtsh -t 1 -rl 5 -timeout 10 -o /out/result.jsonl
limits:   --cap-drop ALL --security-opt no-new-privileges --read-only --pids-limit 256
          --memory 512m --cpus 1 --timeout 120 (subfinder manifest budget is 900s)
EOF

log "subfinder: running $AEGIS_LAB_SUBFINDER_IMAGE against the local passive stub for $LAB_ZONE"
if ! podman run --rm --name aegis-lab-subfinder-run --label "$RUN_LABEL" \
  --network "$LAB_NETWORK" --add-host "crt.sh:$PASSIVE_IP" \
  --cap-drop ALL --security-opt no-new-privileges \
  --read-only --tmpfs /tmp:size=256m \
  --pids-limit 256 --memory 512m --cpus 1 \
  --timeout 120 \
  --userns=keep-id --user "$(id -u):$(id -g)" \
  -e HOME=/tmp -e "SSL_CERT_FILE=/lab-tls/ca.crt" \
  -v "$TLS_DIR/ca.crt:/lab-tls/ca.crt:ro,z" \
  -v "$run_dir/out:/out:Z" \
  "$AEGIS_LAB_SUBFINDER_IMAGE" -silent -json -d "$LAB_ZONE" -sources crtsh \
  -t 1 -rl 5 -timeout 10 -o /out/result.jsonl \
  >"$run_dir/stdout.jsonl" 2>"$run_dir/stderr.txt"; then
  tail -20 "$run_dir/stderr.txt" >&2 || true
  die "subfinder run failed (evidence: $run_dir)"
fi

sha256sum "$run_dir/out/result.jsonl" >"$run_dir/result.sha256"
python3 "$LAB_SCRIPTS/compare_results.py" subfinder \
  --expected "$FIXTURES_DIR/subfinder.expected.json" \
  --actual "$run_dir/out/result.jsonl" | tee "$run_dir/comparison.txt"

log "subfinder: raw $run_dir/out/result.jsonl ($(cat "$run_dir/result.sha256"))"
